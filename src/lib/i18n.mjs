export function isLocale(value) { return typeof value === 'string' && LOCALES.includes(value); }
export function normalizeLocale(value) { return isLocale(value) ? value : 'fr'; }
export function ui(locale, key) { return UI[normalizeLocale(locale)]?.[key] ?? UI.fr[key] ?? key; }
export function localizedLabel(value, locale, fallback = 'fr') {
  // Only use a supplied literal realization: no machine translation or ID rewrites.
  if (typeof value === 'string') return value;
  if (!value || typeof value !== 'object' || Array.isArray(value)) return '';
  const language = normalizeLocale(locale);
  const result = value[language] ?? value[fallback] ?? value.fr ?? value.en;
  return typeof result === 'string' ? result : '';
}
export function hasLocalizedLabel(value, locale) {
  return Boolean(value && typeof value === 'object' && !Array.isArray(value) && typeof value[normalizeLocale(locale)] === 'string' && value[normalizeLocale(locale)].trim());
}
export function localizedEntityLabel(entity, locale) {
  if (!entity || typeof entity !== 'object') return '';
  return localizedLabel(entity.labels ?? entity.localizedLabels ?? entity.label, locale) || (typeof entity.label === 'string' ? entity.label : '') || entity.id || '';
}
