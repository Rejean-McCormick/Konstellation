export function uiFinish(locale, key) {
  const lang = normalizeLocale(locale);
  return UI_FINISH[lang]?.[key] ?? uiBase(lang, key);
}
export function localizedRecipeLabel(recipe, locale) {
  if (!recipe || typeof recipe !== 'object') return '';
  const key = RECIPE_KEYS[recipe.id];
  // A reader-provided/custom recipe name is data, not generic UI; do not replace it.
  if (!key || recipe.label !== RECIPE_CANONICAL_FRENCH[recipe.id]) return recipe.label || recipe.id || '';
  return uiFinish(locale, key);
}
