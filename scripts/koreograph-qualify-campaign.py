#!/usr/bin/env python3
"""Qualify only SVG outputs explicitly listed in a Koreograph manifest; never publish."""
import argparse, hashlib, importlib.util, json, re
from pathlib import Path
spec=importlib.util.spec_from_file_location('kgcheck',Path(__file__).with_name('koreograph-runtime-check.py'))
check=importlib.util.module_from_spec(spec);spec.loader.exec_module(check)

def digest(raw): return hashlib.sha256(raw).hexdigest()
def read_regular(file,limit):
    if file.is_symlink() or not file.is_file() or file.stat().st_size>limit: raise ValueError('Fichier régulier hors budget.')
    raw=file.read_bytes()
    if len(raw)>limit: raise ValueError('Fichier hors budget.')
    return raw

def safe_child(root,name):
    # Manifest names are generated by the CLI, never arbitrary paths.
    if not isinstance(name,str) or not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9._-]{0,150}',name) or name in ('.','..'): raise ValueError('Nom de sortie invalide.')
    file=root/name
    if file.is_symlink() or file.resolve().parent!=root.resolve(): raise ValueError('Chemin de sortie refusé.')
    return file

def collect(manifest):
    raw=read_regular(manifest,1024*1024);m=json.loads(raw);root=manifest.parent;files=[]
    if m.get('publicationAuthorized') is not False: raise ValueError('Manifeste privé obligatoire.')
    if m.get('state')!='review': raise ValueError('Production incomplète ; réparer avant qualification.')
    if m.get('format')=='koreograph.multi-batch/0.1':
        jobs=m['jobs']
        if not 1<=len(jobs)<=12: raise ValueError('Budget de lots.')
        for job in jobs:
            if job.get('status')!='review' or not re.fullmatch(r'bundle-\d{2}',job.get('id','')): raise ValueError('Lot non prêt.')
            folder=safe_child(root,job['id']);child=safe_child(folder,'manifest.json')
            if job.get('manifest')!=job['id']+'/manifest.json' or digest(read_regular(child,1024*1024))!=job.get('manifestSha256'): raise ValueError('Manifeste enfant altéré.')
            nested,_=collect_single(child);files.extend((job['id']+'/'+name,file,sha) for name,file,sha in nested)
    else: files,_=collect_single(manifest)
    if not 1<=len(files)<=120 or len({x[0] for x in files})!=len(files): raise ValueError('Aucun SVG animé ou budget/identité invalide.')
    return files,digest(raw)

def collect_single(manifest):
    raw=read_regular(manifest,1024*1024);m=json.loads(raw);root=manifest.parent
    if m.get('publicationAuthorized') is not False or m.get('state')!='review': raise ValueError('Production non privée ou incomplète.')
    fmt=m.get('format');entries=m['outputs'] if fmt=='koreograph.local-batch/0.1' else m['files'] if fmt=='koreograph.specialized-production/0.1' else None
    if not isinstance(entries,list) or not 1<=len(entries)<=20: raise ValueError('Format de manifeste ou budget inconnu.')
    files=[]
    for e in entries:
        if fmt=='koreograph.local-batch/0.1':
            if e.get('status')!='success': raise ValueError('Sortie non réussie.')
            if e.get('format')!='svg': continue
        elif e.get('file')!='animation.svg': continue
        name=e.get('file');f=safe_child(root,name);sha=e.get('sha256');raw_svg=read_regular(f,32*1024*1024)
        if not isinstance(sha,str) or digest(raw_svg)!=sha or e.get('bytes')!=len(raw_svg): raise ValueError('SVG altéré.')
        files.append((name,f,sha))
    return files,digest(raw)

def run(manifest,browsers,chromium=None):
    files,manifest_sha=collect(manifest);results=[]
    for name,file,sha in files:
        for browser in browsers:
            try:
                if digest(read_regular(file,32*1024*1024))!=sha: raise ValueError('SVG modifié après lecture du manifeste.')
                result=check.qualify(file,chromium if browser=='chromium' else None,browser)
                if result.get('sha256')!=sha: raise ValueError('SVG modifié pendant le contrôle.')
            except Exception:
                result={'state':'fail','sha256':sha,'browser':browser,'diagnostics':['R-EXECUTION-FAILED'],'publicationAuthorized':False}
            results.append({'file':name,**result})
    state='fail' if any(r['state']=='fail' for r in results) else 'review' if any(r['state']!='pass' for r in results) else 'pass'
    return {'format':'koreograph.runtime-campaign/0.1','manifestSha256':manifest_sha,'publicationAuthorized':False,'state':state,'scope':'SVG SMIL échantillonné uniquement ; pas une qualification d’accès, d’accessibilité complète ou de publication.','results':results}

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('manifest',type=Path);parser.add_argument('--browsers',default='chromium');parser.add_argument('--chromium');parser.add_argument('--report',required=True,type=Path);args=parser.parse_args()
    browsers=args.browsers.split(',')
    if len(set(browsers))!=len(browsers) or any(b not in ('chromium','firefox','webkit') for b in browsers): parser.error('Navigateurs : chromium,firefox,webkit.')
    if args.report.exists(): parser.error('Rapport existant ; choisir un nouveau chemin.')
    report=run(args.manifest,browsers,args.chromium)
    with args.report.open('x',encoding='utf-8') as f: json.dump(report,f,ensure_ascii=False,indent=2);f.write('\n')
    print(json.dumps({'state':report['state'],'checks':len(report['results']),'report':str(args.report)},ensure_ascii=False))
    raise SystemExit(0 if report['state']=='pass' else 2 if report['state']=='review' else 1)
