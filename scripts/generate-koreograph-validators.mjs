import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const ajv = new Ajv2020({ strict: true, strictTuples: false, code: { source: true, esm: true } });
const validators = {};
for (const name of ['score', 'bundle']) {
  const schema = JSON.parse(readFileSync(new URL(`../docs/koreograph/schemas/${name}.schema.json`, import.meta.url)));
  ajv.addSchema(schema);
  validators[name] = schema.$id;
}
const code = standaloneCode(ajv, validators)
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
const output = '// Generated by scripts/generate-koreograph-validators.mjs.\n'
  + 'import length from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = length.default;\n'
  + code + '\n';
if (code.includes('require(')) throw Error('Unexpected validator runtime dependency');
const file = new URL('../src/lib/koreograph/validators.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output) throw Error('Koreograph validators must be regenerated');
} else {
  writeFileSync(file, output);
}
